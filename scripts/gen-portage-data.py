#!/usr/bin/env python3
"""Regenerate the Portage data modules from a Gentoo tree (read only):

    python3 scripts/gen-portage-data.py /var/db/repos/gentoo

Writes src/gentoo_installer/profiles_data.py (the amd64 23.0 profiles of profiles.desc) and
src/gentoo_installer/usedesc_data.py (use.desc and the VIDEO_CARDS values of profiles/desc/video_cards.desc).
Run it when the pinned tree moves; tests/test_port_data.py checks the shape of the result.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

# VIDEO_CARDS values that mean something on a PC (the other values are for ARM boards and other machines).
PC_VIDEO_CARDS = (
    "amdgpu", "ast", "d3d12", "dummy", "fbdev", "geode", "i915", "i965", "intel", "lavapipe", "mga", "nouveau", "nvidia", "nvk",
    "qxl", "r100", "r128", "r200", "r300", "r600", "radeon", "radeonsi", "siliconmotion", "vesa", "via", "virgl", "virtualbox",
    "vmware", "zink",
)


def main(tree: Path, source: Path) -> None:
    profiles = []
    for line in (tree / "profiles/profiles.desc").read_text().splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[0] == "amd64" and fields[1].startswith("default/linux/amd64/23.0"):
            profiles.append((fields[1], fields[2]))
    (source / "profiles_data.py").write_text(
        '"""PORT: the amd64 23.0 profiles of the pinned tree (generated by scripts/gen-portage-data.py, do not edit)."""\n\n'
        f"TREE_DATE = {date.today().isoformat()!r}\n\n"
        "# (profile path, stability): stable | dev | exp\n"
        "AMD64_PROFILES: tuple[tuple[str, str], ...] = (\n" + "".join(f"    {item!r},\n" for item in profiles) + ")\n")

    global_use: dict[str, str] = {}
    for line in (tree / "profiles/use.desc").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            name, _, description = line.partition(" - ")
            global_use[name.strip()] = description.strip()
    cards: dict[str, str] = {}
    for line in (tree / "profiles/desc/video_cards.desc").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            name, _, description = line.partition(" - ")
            name = name.strip()
            if name in PC_VIDEO_CARDS:
                cards[name] = description.replace("VIDEO_CARDS setting to ", "").strip()
    text = ['"""PORT: global USE flag descriptions and VIDEO_CARDS values of the pinned tree (generated by scripts/gen-portage-data.py, do not edit)."""\n\n',
            f"TREE_DATE = {date.today().isoformat()!r}\n\n", "GLOBAL_USE: dict[str, str] = {\n"]
    text += [f"    {name!r}: {description!r},\n" for name, description in sorted(global_use.items())]
    text += ["}\n\nVIDEO_CARDS: dict[str, str] = {\n"]
    text += [f"    {name!r}: {description!r},\n" for name, description in sorted(cards.items())]
    text += ["}\n"]
    (source / "usedesc_data.py").write_text("".join(text))


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    main(Path(sys.argv[1]), root / "src/gentoo_installer")
